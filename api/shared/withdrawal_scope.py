"""탈퇴하면 무엇이 남고 무엇이 지워지나 — **경계는 이 파일 한 곳에만 있다.**

판정 코드는 이 목록을 돌 뿐 무엇을 지울지 정하지 않는다. 정책이 바뀌면
(예: "결제 기록은 5년 보존") 아래 표만 고친다. 값이 두 곳에 있으면 반드시
갈라진다 — `free_scope.py` 머리말과 같은 이유다.

정본은 `docs/legal_draft_v1.html` §03 제4조·제6조다.

## 길이 둘이다 — 헷갈리면 사고가 난다

  **가리기**(`maskAccount`)  ← **탈퇴는 이쪽이다** (기획 확정 2026-08-29)
      계정과 학습 데이터를 **그대로 두고** 이름·이메일만 되돌릴 수 없게 가린다.
      학생들이 어떻게 공부하는지 참고하려는 것이고, 학교는 목록에서 못 보고
      마스터만 본다. 아래 `MASK_*` 가 그 규칙이다.

  **지우기**(`purgeAccount`)  ← 진짜 삭제. 아래 `PURGE_MODELS` 가 그 목록이다
      개인정보 삭제권 행사(제6조)처럼 **정말 지워야 할 때만** 부른다.
      탈퇴는 이제 이 길로 오지 않는다.

**둘 다 되돌릴 수 없다.** 다른 것은 남는 것이 있느냐뿐이다.

**왜 `purgeAccount` 는 전부 지우나** (탈퇴가 아니라 삭제권 행사 쪽 이야기다).
남길 근거가 되는 표가 아직 하나도 없다:

  · 결제가 없다 → 전자상거래법의 보존의무가 걸리는 표가 없다
  · 학습 기록을 남길 근거는 "서비스 품질 개선" 인데 그 범위가 **미정**이다
    (legal_draft §01 의 「전량 보관」)
  · 개인정보 보호법의 기본은 목적을 다하면 **지체 없이 파기**다

그러니 지금 단계에서 안전한 기본값은 "다 지운다" 다. 결제가 붙으면 그때
`ko_payment` 를 예외로 두고 보존기간을 여기 적는다.

**예외가 하나 있다 — 지우는 대신 사람만 지우는 표다.** `ANONYMIZE_MODELS`
(지금은 `ko_signup_code_use` 하나). 보존기간을 두는 것이 아니라 개인 연결을
끊는 것이라 위 논리와 어긋나지 않는다 — 까닭은 그 목록 위에 적었다.

**빈칸이었던 것 하나 — 정해졌다(2026-08-29).** 탈퇴한 계정의 이메일로
**다시 가입할 수 있다.** 이메일을 가리면 `ko_user.email` 의 UNIQUE 가 저절로
풀려서 추가 작업이 없다. 못 하게 하려면 원본 이메일의 해시를 남겨야 하는데,
같은 메일이면 같은 해시라 **사실상 이메일을 보관하는 것**이고 「가린다」는 약속과
부딪힌다. 대신 옆에 옛 계정이 가려진 채 남아 있어 **마스터도 둘이 같은 사람인지
알 수 없다** — 이으려면 이메일을 안 가려야 하고, 그건 가린 것이 아니다.
"""
from persistence import model

# ── 가리기 — 탈퇴가 실제로 타는 길 ──────────────────────────────
#
# **되돌릴 수 없다.** 원본을 어디에도 남기지 않고 덮어쓴다. 되돌릴 수 있게
# 만들면 그것은 파기가 아니라 가명처리이고, 개인정보보호법에서 가명정보는
# 여전히 개인정보다 — 제4조의 약속과 다른 물건이 된다.

MASK_CHAR = "○"


def maskName(name: str) -> str:
    """어절마다 첫 글자만 남긴다 (기획 확정 2026-08-29).

        김수현          → 김○○
        Nguyen Thi Mai → N○○○○○ T○○ M○○

    **어절 단위인 이유는 학생 대부분이 외국인이기 때문이다.** 연세 글로벌
    한국어라 이름이 한글·로마자·길이가 제각각인데, 「앞뒤 한 글자씩」 같은
    규칙은 두 글자 이름을 하나도 못 가리고 `Mai` 같은 짧은 이름을 그대로
    드러낸다. 첫 글자만 남기면 어느 표기든 같은 정도로 가려진다.

    길이는 남긴다 — 이름 길이만으로는 사람을 못 찾는다. 이메일과 다르다.
    """
    if not name:
        return MASK_CHAR
    parts = []
    for word in str(name).split():
        parts.append(word[0] + MASK_CHAR * (len(word) - 1) if len(word) > 1 else word)
    return " ".join(parts) or MASK_CHAR


def maskEmail(email: str, userId) -> str:
    """앞 한 글자만 남기고 도메인까지 가린다. 뒤에 계정 id 를 붙인다.

        soohyeon@yonsei.ac.kr → s○○○@○○○.14

    **도메인을 남기지 않는다.** 남기면 학교와 국적이 그대로 샌다 —
    이름을 가려 놓고 `@yonsei.ac.kr` 를 남기면 가린 뜻이 없다.

    **길이도 남기지 않는다.** ○ 을 세 개로 고정한다. 이름과 달리 이메일은
    길이가 후보를 크게 좁힌다.

    **id 를 붙이는 것은 장식이 아니다.** `ko_user.email` 에 UNIQUE 가 걸려
    있어서(`ix_ko_user_email`), 가린 값이 겹치면 **둘째 탈퇴가 중복키로
    터진다.** `s` 로 시작하는 이메일은 흔하다.
    """
    first = (str(email).strip()[:1] or MASK_CHAR)
    return f"{first}{MASK_CHAR * 3}@{MASK_CHAR * 3}.{userId}"


